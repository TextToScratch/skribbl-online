// Builds the practice-mode drawings (src/lib/recordings.ts): stroke tokens in the same format the
// drawer streams over the cloud (see src/Pen.ts), so the Bot "draws" them through the normal replay path.
import fs from "node:fs";

const pt = (x, y) => String(Math.round(Math.max(0, Math.min(339, x))) * 244 + Math.round(Math.max(0, Math.min(243, y)))).padStart(5, "0");
const color = (c, size) => `91${String(c).padStart(2, "0")}${size}`;
const UP = "92000", FILL = "94000";
const line = (pts) => [...pts.map(([x, y]) => pt(x, y)), UP];
const circle = (cx, cy, r, n = 24, a0 = 0, a1 = 360) =>
  Array.from({ length: n + 1 }, (_, i) => { const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180; return [cx + r * Math.cos(a), cy + r * Math.sin(a)]; });
const disc = (cx, cy, r) => { const out = []; for (let rr = r; rr > 0; rr -= 8) out.push(...line(circle(cx, cy, rr, 20))); return out; };

// palette indexes: 0 white 1 black 4 red 6 orange 8 yellow 10 green 14 cyan 16 blue 18 purple 20 pink 24 brown
