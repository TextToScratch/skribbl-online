const words = Object.keys(drawings);
const src = `// Generated by scripts/recordings.mjs: practice-mode drawings for the Bot, as stroke tokens.
export const REC_WORDS: string[] = ${JSON.stringify(words)};
/** One drawing per item: tokens joined into one digit string (5 digits each). */
export const REC_DATA: string[] = ${JSON.stringify(words.map((w) => drawings[w].join("")))};
`;
fs.mkdirSync("src/lib", { recursive: true });
fs.writeFileSync("src/lib/recordings.ts", src);
